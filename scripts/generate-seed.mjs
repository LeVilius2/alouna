import fs from 'node:fs';
import crypto from 'node:crypto';
import { DEFAULT_RULES } from '../packages/core/src/rules/defaults.ts';

const source = new URL('../supabase/seed/wgs84coord.geojson', import.meta.url);
const output = new URL('../supabase/seed/seed.sql', import.meta.url);
const quote = (value) => `'${String(value).replaceAll("'", "''")}'`;
const number = (value) => (value == null ? 'null' : String(value));
const uuid = (name) => {
  const bytes = crypto
    .createHash('sha256')
    .update(`alouna:legacy-seed:v1:${name}`)
    .digest()
    .subarray(0, 16);
  bytes[6] = (bytes[6] & 15) | 80;
  bytes[8] = (bytes[8] & 63) | 128;
  const h = bytes.toString('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
};
const mapping = {
  Musu: { name: 'Our plot', category: 'walkable_area', enabled: true, owner: 'Ours' },
  Neringos: { name: "Neringa's plot", category: 'walkable_area', enabled: false, owner: 'Neringa' },
  Kaimyno: {
    name: "Neighbour's plot",
    category: 'walkable_area',
    enabled: false,
    owner: 'Neighbour',
  },
  Ežeras: { name: 'Lake', category: 'water', enabled: true, owner: '' },
  'Vyžintų žemė': {
    name: 'Vyžintai land',
    category: 'walkable_area',
    enabled: false,
    owner: 'Vyžintai',
  },
  'Kažkieno sklypas': {
    name: 'Other plot',
    category: 'walkable_area',
    enabled: false,
    owner: 'Other',
  },
  'Valstybinė žemė': {
    name: 'State land',
    category: 'walkable_area',
    enabled: false,
    owner: 'State',
  },
};
const data = JSON.parse(fs.readFileSync(source, 'utf8'));
const lines = [
  '-- Generated by scripts/generate-seed.mjs. Original GeoJSON is retained unchanged.',
  '-- Idempotent: never overwrites reviewed edits or owner-adjusted rules.',
  'begin;',
];
for (const r of DEFAULT_RULES)
  lines.push(
    `insert into public.category_rules(category,label,passable,cost,buffer_m,warn_m,overrides,priority,color) values (${quote(r.category)},${quote(r.label)},${r.passable},${r.cost},${r.buffer_m},${number(r.warn_m)},array[${r.overrides.map(quote).join(',')}]::text[],${r.priority},${quote(r.color)}) on conflict(category) do nothing;`,
  );
for (const feature of data.features) {
  const original = feature.properties.name,
    entry = mapping[original];
  if (!entry) {
    if (feature.geometry.type === 'LineString' && original.startsWith('Žemėlapio ')) continue;
    throw new Error(`Unmapped seed feature: ${original}`);
  }
  if (feature.geometry.type !== 'Polygon') throw new Error('Unexpected seed geometry');
  lines.push(
    `do $seed$ declare g extensions.geometry := extensions.st_setsrid(extensions.st_geomfromgeojson(${quote(JSON.stringify(feature.geometry))}),4326); begin
  if extensions.st_isvalid(g) then
    insert into public.features(id,name,category,geom,enabled,owner_label,reviewed,source,notes) values (${quote(uuid(original))},${quote(entry.name)},${quote(entry.category)},g,${entry.enabled},${quote(entry.owner)},true,'import',${quote(`Legacy source name: ${original}`)}) on conflict(id) do nothing;
  else
    insert into alouna_private.seed_rejections(source_id,source_name,feature,reason) values (${quote(uuid(original))},${quote(original)},${quote(JSON.stringify(feature))}::jsonb,extensions.st_isvalidreason(g)) on conflict(source_id) do nothing;
  end if;
end $seed$;`,
  );
}
lines.push('commit;', '');
const result = lines.join('\n');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(output, 'utf8') !== result)
    throw new Error('Seed is stale: run pnpm seed:generate');
  console.log('Seed matches the retained GeoJSON and current core rules.');
} else {
  fs.writeFileSync(output, result);
  console.log('Generated supabase/seed/seed.sql');
}
